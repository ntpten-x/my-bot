-- Owner-managed AI providers with encrypted keys, limits, usage, and cooldowns.
CREATE TABLE "AiProvider" (
    "id" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "preset" TEXT NOT NULL DEFAULT 'custom',
    "kind" TEXT NOT NULL DEFAULT 'openai',
    "baseUrl" TEXT NOT NULL DEFAULT '',
    "model" TEXT NOT NULL DEFAULT '',
    "apiKeyEnc" TEXT,
    "apiKeyHint" TEXT,
    "enabled" BOOLEAN NOT NULL DEFAULT true,
    "priority" INTEGER NOT NULL DEFAULT 100,
    "tasks" TEXT NOT NULL DEFAULT 'classify',
    "limitPerMinute" INTEGER,
    "limitPerDay" INTEGER,
    "resetHourUtc" INTEGER NOT NULL DEFAULT 0,
    "origin" TEXT NOT NULL DEFAULT 'user',
    "usageDay" TEXT,
    "requestsToday" INTEGER NOT NULL DEFAULT 0,
    "tokensToday" INTEGER NOT NULL DEFAULT 0,
    "requestsTotal" INTEGER NOT NULL DEFAULT 0,
    "tokensTotal" INTEGER NOT NULL DEFAULT 0,
    "errorsTotal" INTEGER NOT NULL DEFAULT 0,
    "lastLatencyMs" INTEGER,
    "lastUsedAt" TIMESTAMP(3),
    "lastError" TEXT,
    "lastErrorAt" TIMESTAMP(3),
    "cooldownUntil" TIMESTAMP(3),
    "cooldownReason" TEXT,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "AiProvider_pkey" PRIMARY KEY ("id")
);
CREATE INDEX "AiProvider_priority_idx" ON "AiProvider"("priority");